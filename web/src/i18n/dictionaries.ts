export const dictionaries: Record<Lang, Dictionary> = { en, he };

export function format(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (m, key: string) =>
    key in params ? String(params[key]) : m,
  );
}

export function translate(lang: Lang, key: MessageKey, params?: Record<string, string | number>): string {
  return format(dictionaries[lang][key], params);
}

const HEBREW_ORDINALS = ['ראשון', 'שני', 'שלישי', 'רביעי', 'חמישי', 'שישי', 'שביעי', 'שמיני', 'תשיעי', 'עשירי'];

/** "1st", "2nd"… in English; "ראשון", "שני"… in Hebrew (used in `betOrder`). */
export function ordinal(lang: Lang, n: number): string {
  if (lang === 'he') return HEBREW_ORDINALS[n - 1] ?? String(n);
  const mod100 = n % 100;
  if (mod100 >= 11 && mod100 <= 13) return `${n}th`;
  const suffix = ({ 1: 'st', 2: 'nd', 3: 'rd' } as Record<number, string>)[n % 10] ?? 'th';
  return `${n}${suffix}`;
}
